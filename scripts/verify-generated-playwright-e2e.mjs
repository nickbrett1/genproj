#!/usr/bin/env node
/**
 * End-to-end check: generate a `sveltekit + playwright` project, install it,
 * and ACTUALLY RUN the emitted Playwright suite against a real Chromium reached
 * over the DevTools Protocol.
 *
 * Why this exists
 * ---------------
 * The hybrid fixtures (shared-CDP when a Chrome answers, bundled Chromium
 * otherwise) and the smoke test were merged without ever being executed. A
 * text pin can prove the fixtures *say* they never call `browser.close()`; only
 * a real run can prove they do not. This script therefore:
 *
 *   1. generates the project and asserts the emitted shape;
 *   2. starts a Chromium with `--remote-debugging-port`;
 *   3. starts the generated app with `npm run dev` (`vite dev`, NOT `preview`:
 *      preview is adapter-dependent and this check must not be coupled to an
 *      adapter choice) on 127.0.0.1:4173, matching playwright.config.js's
 *      default baseURL, with UI_BASE_URL set explicitly;
 *   4. runs `npm run test:e2e` with PLAYWRIGHT_CDP_URL pointing at the Chromium
 *      it launched and CI=1;
 *   5. asserts the run went through the `shared-cdp` tier, not
 *      `bundled-chromium` — this is the branch real devcontainers use;
 *   6. asserts, after the suite exits, that the Chromium it launched is STILL
 *      ALIVE. That turns "the fixtures must never close the shared browser"
 *      from prose into a runtime proof: closing it fails this check.
 *
 * Honest limit
 * ------------
 * This proves the suite runs and that the `connectOverCDP` path works against a
 * Chromium whose version matches the project's own `@playwright/test` (the
 * binary is installed by the project and located via
 * `npx playwright install --dry-run`). It does NOT prove compatibility with the
 * estate's Chrome 158, which only a run inside a real devcontainer can show.
 * A passing run here is a necessary, not a sufficient, condition.
 *
 * Usage:
 *   node scripts/verify-generated-playwright-e2e.mjs
 *
 * Environment:
 *   GENPROJ_E2E_KEEP=1       keep the generated project for inspection.
 *   GENPROJ_E2E_APP_PORT     app port, default 4173. Only a local escape hatch
 *                            for a busy 4173; CI leaves it unset.
 */

import { spawn } from "node:child_process";
import fs from "node:fs";
import net from "node:net";
import os from "node:os";
import path from "node:path";

import { generateAllFiles } from "../src/generator/file-generator.js";

const APP_PORT = Number(process.env.GENPROJ_E2E_APP_PORT || 4173);
const APP_URL = `http://127.0.0.1:${APP_PORT}`;

const context = {
  projectName: "genproj-e2e-playwright",
  description: "Generated by verify-generated-playwright-e2e.mjs",
  capabilities: ["devcontainer-node", "sveltekit", "playwright"],
  configuration: {},
  registryNamespace: "genproj-e2e",
};

const workDir = fs.mkdtempSync(
  path.join(os.tmpdir(), "genproj-e2e-playwright-"),
);
const failures = [];

/** Resources to tear down in the finally block, in reverse start order. */
let chrome = null;
let devServer = null;

function fail(message) {
  console.error(`\n✗ ${message}`);
  failures.push(message);
}

function check(ok, description, detail) {
  if (ok) {
    console.log(`  PASS  ${description}`);
    return;
  }
  const suffix = detail ? `\n        ${detail}` : "";
  console.log(`  FAIL  ${description}${suffix}`);
  failures.push(description);
}

/**
 * Spawn and wait. `capture` keeps stdout+stderr in memory (needed to inspect
 * the Playwright run for the browser tier) while still echoing it; without it
 * the child inherits the terminal, as the other verify scripts do.
 */
function run(label, command, args, options = {}) {
  console.log(`\n$ ${[command, ...args].join(" ")}`);
  return new Promise((resolve) => {
    const child = spawn(command, args, {
      cwd: options.cwd ?? workDir,
      env: { ...process.env, ...(options.env ?? {}) },
      // stdin CLOSED: a prompt with an open pipe waits forever, and a timed-out
      // run must fail rather than wedge CI.
      stdio: ["ignore", "pipe", "pipe"],
    });
    let output = "";
    const collect = (stream, sink) => {
      stream.on("data", (chunk) => {
        output += chunk.toString();
        sink.write(chunk);
      });
    };
    collect(child.stdout, process.stdout);
    collect(child.stderr, process.stderr);
    const timer = setTimeout(() => {
      console.error(`\n✗ ${label}: timed out`);
      child.kill("SIGKILL");
    }, options.timeoutMs ?? 600_000);
    child.on("close", (code) => {
      clearTimeout(timer);
      if (code !== 0) fail(`${label}: exited ${code}`);
      resolve({ ok: code === 0, output });
    });
    child.on("error", (error) => {
      clearTimeout(timer);
      fail(`${label}: could not run ${command}: ${error.message}`);
      resolve({ ok: false, output });
    });
  });
}

/** A free TCP port on 127.0.0.1. */
function freePort() {
  return new Promise((resolve, reject) => {
    const server = net.createServer();
    server.unref();
    server.on("error", reject);
    server.listen(0, "127.0.0.1", () => {
      const { port } = server.address();
      server.close(() => resolve(port));
    });
  });
}

async function waitForHttp(url, timeoutMs, label, quiet = false) {
  const deadline = Date.now() + timeoutMs;
  while (Date.now() < deadline) {
    try {
      const response = await fetch(url, { signal: AbortSignal.timeout(1_000) });
      if (response.ok) return true;
    } catch {
      // Not up yet.
    }
    await new Promise((resolve) => setTimeout(resolve, 250));
  }
  if (!quiet) fail(`${label}: no answer at ${url} within ${timeoutMs}ms`);
  return false;
}

/**
 * The version-matched Chromium binary. Playwright's `--dry-run` prints the
 * install location it would use for this project's own @playwright/test; the
 * archive layout differs by platform (`chrome-linux/`, `chrome-linux-arm64/`),
 * so the executable is located by walking that directory.
 */
function chromiumBinaryFromDryRun(output) {
  const match =
    /\(playwright chromium v\d+\)[\s\S]*?Install location:\s*(\S+)/.exec(
      output,
    );
  if (!match) return null;
  return findExecutableNamedChrome(match[1]);
}

function findExecutableNamedChrome(dir) {
  if (!fs.existsSync(dir)) return null;
  const stack = [dir];
  while (stack.length > 0) {
    const current = stack.pop();
    for (const entry of fs.readdirSync(current, { withFileTypes: true })) {
      const full = path.join(current, entry.name);
      if (entry.isDirectory()) stack.push(full);
      else if (
        entry.name === "chrome" &&
        (fs.statSync(full).mode & 0o111) !== 0
      ) {
        return full;
      }
    }
  }
  return null;
}

function killTree(child) {
  if (!child || child.exitCode !== null) return;
  try {
    // Negative pid: the whole process group. npm and vite are two processes,
    // and killing only the npm wrapper strands vite holding the port.
    process.kill(-child.pid, "SIGKILL");
  } catch {
    try {
      child.kill("SIGKILL");
    } catch {
      // Already gone.
    }
  }
}

async function main() {
  console.log(
    `Generating a sveltekit + playwright project into ${workDir} ...`,
  );
  const files = await generateAllFiles(context);
  for (const file of files) {
    const target = path.join(workDir, file.filePath);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, file.content);
  }
  console.log(`Wrote ${files.length} files.`);

  // --- (b) the emitted shape, asserted before anything is installed --------
  const exists = (p) => fs.existsSync(path.join(workDir, p));
  const read = (p) => fs.readFileSync(path.join(workDir, p), "utf8");

  check(exists("playwright.config.js"), "playwright.config.js is emitted");
  check(exists("tests/e2e/smoke.e2e.js"), "tests/e2e/smoke.e2e.js is emitted");
  check(exists("tests/e2e/fixtures.js"), "tests/e2e/fixtures.js is emitted");

  const pkg = JSON.parse(read("package.json"));
  check(
    pkg.scripts?.["test:e2e"] === "playwright test",
    'package.json has "test:e2e": "playwright test"',
    `got ${JSON.stringify(pkg.scripts?.["test:e2e"])}`,
  );

  const config = read("playwright.config.js");
  check(
    config.includes("testDir: './tests/e2e'"),
    "playwright.config.js sets testDir: './tests/e2e'",
  );
  check(
    config.includes("testMatch: '**/*.e2e.js'"),
    "playwright.config.js sets testMatch: '**/*.e2e.js'",
  );

  // --- (c) install ---------------------------------------------------------
  const installed = await run(
    "npm install",
    "npm",
    ["install", "--no-audit", "--no-fund", "--loglevel=error"],
    { timeoutMs: 600_000 },
  );
  if (!installed.ok) return;

  // --- (d) a Chromium the project's Playwright can talk to -----------------
  const browserInstall = await run(
    "playwright install chromium",
    "npx",
    ["playwright", "install", "chromium"],
    { timeoutMs: 600_000 },
  );
  if (!browserInstall.ok) return;

  const dryRun = await run(
    "playwright install --dry-run chromium",
    "npx",
    ["playwright", "install", "--dry-run", "chromium"],
    { timeoutMs: 120_000 },
  );
  if (!dryRun.ok) return;

  const chromeBinary = chromiumBinaryFromDryRun(dryRun.output);
  check(
    Boolean(chromeBinary),
    "located the project's Playwright-installed Chromium binary",
    chromeBinary
      ? chromeBinary
      : "npx playwright install --dry-run named no path",
  );
  if (!chromeBinary) return;

  const cdpPort = await freePort();
  const cdpUrl = `http://127.0.0.1:${cdpPort}`;
  const profileDir = path.join(workDir, ".cdp-profile");
  console.log(`\nLaunching ${chromeBinary} on ${cdpUrl} ...`);
  chrome = spawn(
    chromeBinary,
    [
      "--headless=new",
      "--no-sandbox",
      "--disable-gpu",
      "--disable-dev-shm-usage",
      `--remote-debugging-port=${cdpPort}`,
      `--user-data-dir=${profileDir}`,
      "about:blank",
    ],
    { stdio: ["ignore", "pipe", "pipe"], detached: true },
  );
  chrome.stdout.on("data", () => {});
  chrome.stderr.on("data", () => {});
  chrome.on("error", (error) =>
    fail(`chromium: could not launch: ${error.message}`),
  );
  const cdpUp = await waitForHttp(
    `${cdpUrl}/json/version`,
    30_000,
    "chromium CDP",
  );
  check(cdpUp, `Chromium answers CDP at ${cdpUrl}`);
  if (!cdpUp) return;

  // --- (e) the dev server, NOT preview ------------------------------------
  console.log(`\nStarting the generated app on ${APP_URL} ...`);
  devServer = spawn(
    "npm",
    [
      "run",
      "dev",
      "--",
      "--port",
      String(APP_PORT),
      "--host",
      "127.0.0.1",
      "--strictPort",
    ],
    {
      cwd: workDir,
      env: { ...process.env, UI_BASE_URL: APP_URL },
      stdio: ["ignore", "pipe", "pipe"],
      detached: true,
    },
  );
  devServer.stdout.on("data", (chunk) => process.stdout.write(chunk));
  devServer.stderr.on("data", (chunk) => process.stderr.write(chunk));
  const appUp = await waitForHttp(APP_URL, 120_000, "dev server");
  check(appUp, `the dev server answers at ${APP_URL}`);
  if (!appUp) return;

  // --- (f) the suite, over the CDP tier -----------------------------------
  const testRun = await run("npm run test:e2e", "npm", ["run", "test:e2e"], {
    env: {
      PLAYWRIGHT_CDP_URL: cdpUrl,
      UI_BASE_URL: APP_URL,
      CI: "1",
    },
    timeoutMs: 300_000,
  });

  // --- (g) it actually used the shared-CDP branch -------------------------
  check(
    testRun.ok,
    "npm run test:e2e exits 0",
    testRun.ok ? undefined : "see the Playwright output above",
  );
  check(
    testRun.output.includes("shared-cdp"),
    "the run names the shared-cdp tier (not bundled-chromium)",
    "a bundled fallback would not exercise the branch real devcontainers use",
  );

  // --- (h) THE KEY ASSERTION: the shared browser survived ------------------
  const chromeAlive =
    chrome.exitCode === null &&
    (await waitForHttp(
      `${cdpUrl}/json/version`,
      5_000,
      "chromium after run",
      true,
    ));
  check(
    chromeAlive,
    "the Chromium we launched is STILL ALIVE after the suite (fixtures never close it)",
    "a closed shared browser means the fixture called browser.close()",
  );
}

main()
  .catch((error) => fail(error?.stack || String(error)))
  .finally(async () => {
    // --- (i) always clean up: dev server, chromium, temp dir --------------
    killTree(devServer);
    killTree(chrome);
    // Give SIGKILL a moment so a kept-for-inspection dir is not half alive.
    await new Promise((resolve) => setTimeout(resolve, 200));

    if (failures.length > 0) {
      console.error(`\n✗ ${failures.length} failure(s):`);
      for (const failure of failures) console.error(`  - ${failure}`);
      process.exitCode = 1;
    } else {
      console.log(
        "\n✓ a generated sveltekit + playwright project runs its emitted suite over shared CDP and leaves the browser alive.",
      );
    }
    if (process.env.GENPROJ_E2E_KEEP === "1" || process.exitCode) {
      console.error(`Generated project kept at ${workDir}`);
    } else {
      fs.rmSync(workDir, { recursive: true, force: true });
    }
  });
