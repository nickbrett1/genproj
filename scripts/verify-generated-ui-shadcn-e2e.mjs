#!/usr/bin/env node
/**
 * End-to-end check: generate a `sveltekit + ui-shadcn` project, install the
 * house theme into it with the real CLI, build it, and read the computed styles
 * back out of the built CSS.
 *
 * Why this exists
 * ---------------
 * Five defects shipped that no unit test could see, because each one is only
 * visible when a *generated* project is *built* and *rendered*. All five were
 * found by hand on 2026-11-14, one run each, and every one of them sat behind
 * ~1029 green tests:
 *
 *   1. `components.json` carried a `registries` block — shadcn/ui (React)
 *      syntax that `shadcn-svelte` ignores entirely, so it advertised a
 *      registry, a bearer token and a pinned version and did nothing.
 *   2. The styling rules named `npx shadcn-svelte@latest add @nb/theme`: a
 *      namespace this CLI does not have, an unpinned CLI, and no `--overwrite`
 *      — without which `add` asks a second question, prints it, and exits 0
 *      having written nothing.
 *   3. `shadcn-svelte` was not a dependency, though the merge injects
 *      `@import "shadcn-svelte/tailwind.css";` — the next build fails.
 *   4. Nothing imported `src/app.css`. SvelteKit imports no stylesheet itself,
 *      so the theme installed into a file nobody loaded: the build passed and
 *      every page was unstyled. Only a computed style shows this.
 *   5. There was no `tsconfig.json` while `components.json` said
 *      `typescript: true`, and the CLI refuses before fetching anything.
 *
 * Usage:
 *   node scripts/verify-generated-ui-shadcn-e2e.mjs
 *
 * Environment:
 *   COMPONENTS_REGISTRY_URL   required. The registry HOST, without a version:
 *                             e.g. http://ryzen:3012/r. It is the same variable
 *                             a generated project documents, and that variable
 *                             is versionless on purpose (spec 028) -- the pin
 *                             is composed onto it, here from the catalog
 *                             default, exactly as the emitted command does.
 *   GENPROJ_E2E_SKIP_RENDER=1 skip the headless computed-style check (the
 *                             compiled-CSS assertions still run). CI must not
 *                             set this: the render check is the one that
 *                             catches defect 4.
 *   GENPROJ_E2E_KEEP=1        keep the generated project for inspection.
 */

import { spawn } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { generateAllFiles } from "../src/generator/file-generator.js";
import {
  NB_THEME_DEFAULT_VERSION,
  SHADCN_CLI_VERSION,
} from "../src/generator/file-generator.js";

const registryUrl = (process.env.COMPONENTS_REGISTRY_URL || "").trim();
if (!registryUrl) {
  console.error(
    "\n✗ COMPONENTS_REGISTRY_URL is required (the registry host, e.g. http://ryzen:3012/r).",
  );
  console.error(
    "  Resolve it the way a consumer does: doppler secrets get COMPONENTS_REGISTRY_URL --project common --config dev --plain",
  );
  process.exit(1);
}

// The secret is the registry HOST. The pin is composed onto it here from the
// catalog default, which is exactly what the emitted install command does
// (`"$(doppler ...)/v1.11.0"`) -- so this check exercises the composition a
// consumer runs, not a differently-shaped value that happens to work.
//
// A version inside the secret used to be required (the base was used verbatim).
// Now it is refused: appending the pin to a versioned host yields
// `/v1.11.0/v1.11.0`, and a secret that carries a version is a second copy of a
// pin that nothing checks (spec 028).
const versionedMatch = registryUrl.match(/\/v(\d+\.\d+\.\d+)\/?$/);
if (versionedMatch) {
  console.error(
    `\n✗ COMPONENTS_REGISTRY_URL must be the host, not a pin — drop the /v${versionedMatch[1]} (spec 028); got ${registryUrl}`,
  );
  process.exit(1);
}
const registryBase = registryUrl.replace(/\/+$/, "");
const themeVersion = NB_THEME_DEFAULT_VERSION;
const pinnedBase = `${registryBase}/v${themeVersion}`;

const context = {
  projectName: "genproj-e2e-ui-shadcn",
  description: "Generated by verify-generated-ui-shadcn-e2e.mjs",
  capabilities: ["devcontainer-node", "sveltekit", "ui-shadcn"],
  configuration: {
    "ui-shadcn": { registryUrl: registryBase, themeVersion },
  },
  registryNamespace: "genproj-e2e",
};

const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "genproj-e2e-ui-"));
const failures = [];

function fail(message) {
  console.error(`\n✗ ${message}`);
  failures.push(message);
}

function check(ok, description, detail) {
  if (ok) {
    console.log(`  PASS  ${description}`);
    return;
  }
  const suffix = detail ? `\n        ${detail}` : "";
  console.log(`  FAIL  ${description}${suffix}`);
  failures.push(description);
}

function run(label, command, args, options = {}) {
  console.log(`\n$ ${[command, ...args].join(" ")}`);
  return new Promise((resolve) => {
    const child = spawn(command, args, {
      cwd: options.cwd ?? workDir,
      env: { ...process.env, ...(options.env ?? {}) },
      // stdin CLOSED: `add` prompts a second question, and with an open pipe it
      // waits on it forever. A timed-out run must fail rather than wedge CI.
      stdio: ["ignore", "inherit", "inherit"],
    });
    const timer = setTimeout(() => {
      console.error(`\n✗ ${label}: timed out`);
      child.kill("SIGKILL");
    }, options.timeoutMs ?? 600_000);
    child.on("close", (code) => {
      clearTimeout(timer);
      if (code !== 0) fail(`${label}: exited ${code}`);
      resolve(code === 0);
    });
    child.on("error", (error) => {
      clearTimeout(timer);
      fail(`${label}: could not run ${command}: ${error.message}`);
      resolve(false);
    });
  });
}

function walk(dir, found = []) {
  for (const entry of fs.readdirSync(dir, { withFileTypes: true })) {
    const full = path.join(dir, entry.name);
    if (entry.isDirectory()) walk(full, found);
    else found.push(full);
  }
  return found;
}

async function main() {
  console.log(`Registry: ${registryBase} (theme ${themeVersion})`);
  console.log(`Composed base: ${pinnedBase}`);
  console.log(`Generating a sveltekit + ui-shadcn project into ${workDir} ...`);

  const files = await generateAllFiles(context);
  for (const file of files) {
    const target = path.join(workDir, file.filePath);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, file.content);
  }
  console.log(`Wrote ${files.length} files.`);

  // --- the emitted shape, asserted before anything is installed -------------
  const read = (p) => fs.readFileSync(path.join(workDir, p), "utf8");
  const components = JSON.parse(read("components.json"));
  check(
    !("registries" in components),
    "components.json has no registries block (React-CLI syntax this CLI ignores)",
  );
  check(
    components.style !== "new-york",
    `components.json names a style this CLI has (${components.style})`,
    "new-york is React vocabulary: the CLI warns and silently substitutes nova",
  );

  const tsconfig = JSON.parse(read("tsconfig.json"));
  check(
    tsconfig?.compilerOptions?.paths?.["$lib"] !== undefined,
    "tsconfig.json exists and carries the $lib alias the CLI resolves",
  );

  const layout = read("src/routes/+layout.svelte");
  check(
    layout.includes('import "../app.css";'),
    "a layout imports src/app.css (SvelteKit imports no stylesheet itself)",
  );

  check(
    read("src/app.css").trim() === '@import "tailwindcss";',
    "src/app.css starts as the bare Tailwind entry the merge expects",
  );

  const rules = read(".agents/.rules/styling_guidelines.md");
  check(
    rules.includes(
      `COMPONENTS_REGISTRY_URL="${pinnedBase}" npx shadcn-svelte@${SHADCN_CLI_VERSION} add theme --yes --overwrite`,
    ),
    "the styling rules carry the versioned, pinned, --overwrite install command",
  );
  // The rules and this check must agree on the composed base -- the whole
  // point is that the pin is composed, so a rule naming a different base would
  // mean the composition drifted from the catalog default.
  check(
    rules.includes(`${pinnedBase}`),
    `the rules name the composed base (${pinnedBase})`,
  );

  // --- install, install the theme, build -----------------------------------
  if (
    !(await run("npm install", "npm", [
      "install",
      "--no-audit",
      "--no-fund",
      "--loglevel=error",
    ]))
  )
    return;

  const before = read("src/app.css");
  const installed = await run(
    "shadcn add theme",
    "npx",
    [
      "--yes",
      `shadcn-svelte@${SHADCN_CLI_VERSION}`,
      "add",
      "theme",
      "--yes",
      "--overwrite",
      "--no-deps-install",
    ],
    {
      env: { COMPONENTS_REGISTRY_URL: pinnedBase, NO_COLOR: "1" },
      timeoutMs: 300_000,
    },
  );
  const after = read("src/app.css");
  check(installed, "add theme exits 0");
  check(
    after !== before && after.includes("@theme inline"),
    "the theme is merged into src/app.css",
    "an unchanged file with an exit 0 is the --overwrite trap",
  );
  // The original regression was not a file: it was a DIRECTORY named app.css
  // at the project root, because the CLI resolved a `files[].target` against
  // basename(tailwindCss) treated as a directory. src/app.css is the real
  // stylesheet the theme is merged into and must exist.
  const strayDir = path.join(workDir, "app.css");
  check(
    !fs.existsSync(path.join(workDir, "src", "nb-theme.css")) &&
      !(fs.existsSync(strayDir) && fs.statSync(strayDir).isDirectory()),
    "no src/nb-theme.css and no directory named app.css at the project root",
  );

  if (!(await run("npm run build", "npm", ["run", "build"]))) return;

  // --- the built CSS, not the source CSS -----------------------------------
  const outputDir = path.join(workDir, ".svelte-kit", "output");
  const cssFiles = walk(outputDir).filter((f) => f.endsWith(".css"));
  const bundle = cssFiles.map((f) => fs.readFileSync(f, "utf8")).join("\n");
  check(
    cssFiles.length > 0,
    `the build emitted CSS (${cssFiles.length} files)`,
  );
  check(
    /--bg:\s*#[0-9a-f]{6}/i.test(bundle),
    "the built bundle carries the theme's --bg token",
    "the source file having it is not enough: nothing may import it",
  );
  check(/\.card\s*\{/.test(bundle), "the built bundle carries the .card rule");

  // --- what a browser actually computes ------------------------------------
  if (process.env.GENPROJ_E2E_SKIP_RENDER === "1") {
    console.log("\n  SKIP  computed-style check (GENPROJ_E2E_SKIP_RENDER=1)");
    return;
  }
  let chromium;
  try {
    ({ chromium } = await import("playwright"));
  } catch {
    fail(
      "playwright is not installed, so the computed-style check cannot run (npm i --no-save playwright)",
    );
    return;
  }
  const browser = await chromium.launch();
  try {
    const page = await browser.newPage();
    // The built CSS goes in as a style tag rather than a file:// link: same
    // bytes the app ships, no origin or subresource questions.
    await page.setContent(
      `<!doctype html><html><body><div class="card" id="c">x</div><span class="pill ok" id="p">y</span></body></html>`,
    );
    await page.addStyleTag({ content: bundle });
    const computed = await page.evaluate(() => {
      const body = getComputedStyle(document.body);
      const token = body.getPropertyValue("--bg").trim();
      const probe = document.createElement("div");
      probe.style.color = token;
      document.body.appendChild(probe);
      const resolved = getComputedStyle(probe).color;
      return {
        token,
        resolved,
        background: body.backgroundColor,
        cardRadius: getComputedStyle(document.querySelector("#c")).borderRadius,
        pillColour: getComputedStyle(document.querySelector("#p")).color,
      };
    });
    console.log(`  note  ${JSON.stringify(computed)}`);
    check(
      computed.background !== "rgba(0, 0, 0, 0)" &&
        computed.background === computed.resolved,
      `body renders --bg (${computed.token} -> ${computed.background})`,
      "transparent means the token is defined but never applied",
    );
    check(
      computed.cardRadius !== "0px",
      `.card renders a radius (${computed.cardRadius})`,
    );
    check(
      computed.pillColour !== computed.background &&
        computed.pillColour !== "rgb(0, 0, 0)",
      `.pill.ok renders its own colour (${computed.pillColour})`,
    );
  } finally {
    await browser.close();
  }
}

main()
  .catch((error) => fail(error?.stack || String(error)))
  .finally(() => {
    if (failures.length > 0) {
      console.error(`\n✗ ${failures.length} failure(s):`);
      for (const failure of failures) console.error(`  - ${failure}`);
      process.exitCode = 1;
    } else {
      console.log(
        "\n✓ a generated sveltekit + ui-shadcn project installs the theme and renders it.",
      );
    }
    if (process.env.GENPROJ_E2E_KEEP === "1" || process.exitCode) {
      console.error(`Generated project kept at ${workDir}`);
    } else {
      fs.rmSync(workDir, { recursive: true, force: true });
    }
  });
