/**
 * Prebuild step: inline every generator template as a JSON string in a single
 * JS module.
 *
 * The ftn monorepo relied on Vite's `?raw` import suffix to inline templates at
 * bundle time. Workers are bundled with esbuild, which has no equivalent for
 * our needs, so we materialise the templates into a plain JS module instead and
 * commit the output (like the old `precompiled-templates.js`).
 *
 * Run via `npm run build:templates` (also wired into `pretest`/`prebuild`).
 */

import { readdir, readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const templatesDir = join(here, "..", "src", "generator", "templates");
const outputFile = join(
  here,
  "..",
  "src",
  "generator",
  "templates.generated.js",
);

const files = (await readdir(templatesDir))
  .filter((name) => name.endsWith(".template"))
  .sort();

const entries = [];
for (const name of files) {
  const content = await readFile(join(templatesDir, name), "utf8");
  entries.push(`\t${JSON.stringify(name)}: ${JSON.stringify(content)}`);
}

const output = `// AUTO-GENERATED by scripts/build-templates.mjs — do not edit by hand.
// Source of truth: src/generator/templates/*.template
/* eslint-disable */

export const templateFiles = {
${entries.join(",\n")}
};

export default templateFiles;
`;

await writeFile(outputFile, output, "utf8");
console.log(`Wrote ${files.length} templates to ${outputFile}`);
