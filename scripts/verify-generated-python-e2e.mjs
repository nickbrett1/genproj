#!/usr/bin/env node
/**
 * End-to-end check: generate a Python project and run *that project's* exact
 * CI sequence against it, for real.
 *
 * Why this exists
 * ---------------
 * Two defects shipped that only show up when a freshly generated Python
 * project runs its own first CI build:
 *
 *   1. The documented `pythonDependencies` example named `mcpo>=0.1.0`, which
 *      does not exist on PyPI. `pip install -e ".[dev]"` is the FIRST command
 *      in CI, so the build died before `python -m build`, `ruff` or `pytest`
 *      ran. Only a real install against PyPI catches this - no mock will.
 *
 *   2. The generated `[tool.ruff]` section set neither `target-version` nor
 *      `select`, so the enabled rule set was inferred (from `requires-python`)
 *      and drifted with the ruff release. `ruff check src tests` could pass
 *      locally and fail in CI. The check below asserts the generated config is
 *      explicit *and* runs ruff with the generated pyproject.toml present (in
 *      the generated directory), which is the only place that rule set applies.
 *
 * The sequence is copied from the generated `.buildkite/pipeline.yml`
 * (see `src/generator/capability-template-utils.js`):
 *
 *   python -m pip install --no-cache-dir -e ".[dev]"
 *   python -m pip install --no-cache-dir build
 *   python -m build
 *   ruff check src tests
 *   pytest -q
 *
 * Usage:
 *   node scripts/verify-generated-python-e2e.mjs
 *
 * Environment:
 *   GENPROJ_E2E_DEPS   JSON array overriding pythonDependencies (default: the
 *                      documented example). Use it to prove the check catches
 *                      an unsatisfiable specifier.
 *   GENPROJ_E2E_KEEP=1 keep the generated project directory for inspection.
 */

import { spawnSync } from "node:child_process";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";

import { generateAllFiles } from "../src/generator/file-generator.js";

// Mirrors the nas-reach-mcp repro: the capability set whose CI runs the five
// commands above, with the documented example runtime dependencies.
const documentedExampleDeps =
  process.env.GENPROJ_E2E_DEPS !== undefined
    ? JSON.parse(process.env.GENPROJ_E2E_DEPS)
    : ["mcp>=1.2.0", "mcpo>=0.0.20", "httpx>=0.27.0"];

const context = {
  projectName: "genproj-e2e-python",
  description: "Generated by verify-generated-python-e2e.mjs",
  capabilities: [
    "devcontainer-python",
    "docker-container",
    "buildkite",
    "doppler",
    "code-quality-python",
    "dependabot",
  ],
  configuration: {
    "docker-container": {
      networkMode: "host",
      exposePort: 3010,
      publishPort: "0.0.0.0:3010:3010",
      registry: "ghcr",
      registryNamespace: "genproj-e2e",
      pythonDependencies: documentedExampleDeps,
    },
  },
  registryNamespace: "genproj-e2e",
};

const workDir = fs.mkdtempSync(path.join(os.tmpdir(), "genproj-e2e-"));

function fail(message) {
  console.error(`\n✗ ${message}`);
  console.error(`  generated project: ${workDir}`);
  process.exitCode = 1;
}

function run(label, command, args, cwd) {
  console.log(`\n$ ${[command, ...args].join(" ")}`);
  const result = spawnSync(command, args, { cwd, stdio: "inherit" });
  if (result.error) {
    fail(`${label}: could not run ${command}: ${result.error.message}`);
    return false;
  }
  if (result.status !== 0) {
    fail(`${label}: exited ${result.status}`);
    return false;
  }
  return true;
}

async function main() {
  console.log(`Generating a Python project into ${workDir} ...`);
  const files = await generateAllFiles(context);

  for (const file of files) {
    const target = path.join(workDir, file.filePath);
    fs.mkdirSync(path.dirname(target), { recursive: true });
    fs.writeFileSync(target, file.content);
  }
  console.log(`Wrote ${files.length} files.`);

  // Defect 2 guard: the ruff config must be explicit, or the rule set is
  // inferred and `ruff check src tests` is not deterministic.
  const pyprojectPath = path.join(workDir, "pyproject.toml");
  const pyproject = fs.readFileSync(pyprojectPath, "utf8");
  if (!/^target-version = /m.test(pyproject)) {
    fail("pyproject.toml pins no [tool.ruff] target-version");
    return;
  }
  if (!/^select = \[/m.test(pyproject)) {
    fail("pyproject.toml pins no [tool.ruff] select");
    return;
  }

  // A venv, because CI's `python` is the image interpreter and this script
  // must not install into the host. `python -m pip` -> `python3 -m pip` here.
  const venv = path.join(workDir, ".venv-e2e");
  if (!run("create venv", "python3", ["-m", "venv", venv], workDir)) return;
  const python = path.join(venv, "bin", "python");

  // --- the exact CI sequence ------------------------------------------------
  if (
    !run(
      "step 1/5 pip install -e .[dev]",
      python,
      ["-m", "pip", "install", "--no-cache-dir", "-e", ".[dev]"],
      workDir,
    )
  )
    return;
  if (
    !run(
      "step 2/5 pip install build",
      python,
      ["-m", "pip", "install", "--no-cache-dir", "build"],
      workDir,
    )
  )
    return;
  if (!run("step 3/5 python -m build", python, ["-m", "build"], workDir))
    return;
  if (
    !run(
      "step 4/5 ruff check",
      python,
      ["-m", "ruff", "check", "src", "tests"],
      workDir,
    )
  )
    return;
  if (!run("step 5/5 pytest -q", python, ["-m", "pytest", "-q"], workDir))
    return;

  console.log("\n✓ generated Python project passed its own CI sequence.");
}

main().catch((error) => {
  fail(error?.stack || String(error));
});

process.on("exit", () => {
  if (process.env.GENPROJ_E2E_KEEP === "1" || process.exitCode) {
    console.error(`Generated project kept at ${workDir}`);
  } else {
    fs.rmSync(workDir, { recursive: true, force: true });
  }
});
